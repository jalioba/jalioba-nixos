local map = vim.keymap.set

-- Быстрое сохранение файла (Ctrl + S или Space + w)
map({ "i", "x", "n", "s" }, "<C-s>", "<cmd>w<cr><esc>", { desc = "Сохранить файл" })
map("n", "<leader>w", "<cmd>w<cr>", { desc = "Сохранить файл" })

-- Навигация между сплитами (окнами) через Ctrl + hjkl
map("n", "<C-h>", "<C-w>h", { desc = "Перейти в левое окно" })
map("n", "<C-j>", "<C-w>j", { desc = "Перейти в нижнее окно" })
map("n", "<C-k>", "<C-w>k", { desc = "Перейти в верхнее окно" })
map("n", "<C-l>", "<C-w>l", { desc = "Перейти в правое окно" })

-- Изменение размера сплитов стрелками
map("n", "<C-Up>", "<cmd>resize +2<cr>", { desc = "Увеличить высоту окна" })
map("n", "<C-Down>", "<cmd>resize -2<cr>", { desc = "Уменьшить высоту окна" })
map("n", "<C-Left>", "<cmd>vertical resize -2<cr>", { desc = "Уменьшить ширину окна" })
map("n", "<C-Right>", "<cmd>vertical resize +2<cr>", { desc = "Увеличить ширину окна" })

-- Перемещение строк вверх/вниз в визуальном режиме (Alt + j/k)
map("v", "<A-j>", ":m '>+1<cr>gv=gv", { desc = "Переместить строку вниз" })
map("v", "<A-k>", ":m '<-2<cr>gv=gv", { desc = "Переместить строку вверх" })

-- Сброс подсветки поиска по нажатию Esc
map({ "i", "n" }, "<esc>", "<cmd>noh<cr><esc>", { desc = "Сбросить подсветку поиска" })
